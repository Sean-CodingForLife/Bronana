/* =========================================================
   eco_global.ts — **全局货币**（一笔，单独一本账）
   ---------------------------------------------------------
   v3 §5.1：
     "**全局货币**：三模块通用。每个模块都要用它，每个模块也都能产出它。
      更像'税'或'行动成本'，不是钱。"

   v3 §9-风险3 与 §9-建议3 都在警告同一件事：
     "全局货币可能变成事实上的通用货币 —— 太容易获得、太通用，
      模块代币边缘化。"
     建议："**行动成本，不是钱**；获取有限，消耗刚性。"

   于是它的设计要点**不是"三模块都能花"**（那是它天然的属性），
   而是**两件事必须同时成立**：
     · **获取有限** —— 它不靠"多打几把"堆起来（否则战斗变成无限产出）
     · **消耗刚性** —— 每个模块的**大动作**都要付它，且不能绕过
   只要有一件不成立，它就会退化成"第二个通用货币"，
   而三个模块代币随之边缘化 —— 那正是 v3 §5.4-错误1 的结局。

   ⚠ 它**单独一本账**，不和任何模块的代币同住：
   同住就意味着"这本账里的东西可以互相换"，而全局货币与模块代币
   **不是兑换关系**（§5.3：兑换只在模块代币之间）。
   ========================================================= */
import { Ledger } from './ledger.ts';

Ledger.define({
  id: 'global',
  owner: 'global',
  name: '全局账本（行动成本）',
  note: '三模块通用的那一笔：它是"做任何事都要付的成本"，不是钱',
  currencies: [
    {
      id: 'material', name: '材料',
      note: '三个模块都产出（战斗的掉落与清间、经营的设施运转、养成的里程碑），' +
        '三个模块也都消耗（战斗里造装备、经营里盖设施、养成里训练与突破）',
      why: '它是三个模块唯一的**共同语言**：没有它，跨模块的成本结构就没法统一，' +
        '每一对模块都得单独定一套兑换率 —— 那正是"统一货币表"的起点。' +
        '⚠ 它的成败不在"通用"，在**获取有限 + 消耗刚性**（v3 §9-建议3）：' +
        '一旦它变得又多又好赚，三个模块代币就都成了摆设'
    }
  ]
});
