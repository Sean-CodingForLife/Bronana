/**
 * 定义一条曲线。
 *
 * `tMin` = **自变量的下限**，默认 1（房间号从 1 起）。
 * 为什么要有这个字段：原式里普遍带着 `Math.max(1, t)`（`equivWave` 的夹取），
 * 而"从几开始"是**所有曲线共有的语义**，不该抄进每一条的公式里 ——
 * 第一版把它留在形状里，于是夹取在**两处**各打了一次，`meter.pace` 在 t=1 处
 * 算出 1 而不是 1.55，而那正是"这一间的怪有多硬"的基准。现在**只在 `at()` 里夹一次**。
 */
function curve(id: string, domain: string, unit: string, shape: string, p: CurveParams, why: string, tMin?: number) {
  if (why === undefined) throw new Error('curve: ' + id + ' 必须写 why（它在回答哪个设计问题）');
  return {
    id: id, domain: domain, unit: unit, shape: shape, p: p, why: why,
    tMin: tMin === undefined ? 1 : tMin
  };
}

