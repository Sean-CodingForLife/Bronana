/* =========================================================
   1. 曲线的**形状**（求值器）
   ---------------------------------------------------------
   一个形状 = 一个纯函数 `(t, p) => number`，`t` 是自变量（从 `origin` 起算），
   `p` 是这条曲线的常量。形状与常量分开之后，"换一种曲线"是一次声明改动，
   而不是去找散在各处的公式。
   ========================================================= */
var SHAPES: Record<string, CurveShapeDef> = {
  linear: {
    params: ['a', 'b'], note: 'a + b·t（每步一样多）',
    eval: function (t, p) { return (p.a as number) + (p.b as number) * t; }
  },
  polynomial: {
    params: ['a', 'b', 'c'], note: 'a + b·t + c·t²（中后期拉长，不成峭壁）',
    eval: function (t, p) { return (p.a as number) + (p.b as number) * t + (p.c as number) * t * t; }
  },
  power: {
    params: ['a', 'k', 'm'], note: 'a + m·t^k（幂律；k<1 = 递减收益）',
    eval: function (t, p) { return (p.a as number) + (p.m as number) * Math.pow(t, p.k as number); }
  },
  exponential: {
    params: ['a', 'r'], note: 'a·r^t（复利；r>1 涨、r<1 收敛）',
    eval: function (t, p) { return (p.a as number) * Math.pow(p.r as number, t); }
  },
  /** 封顶：先按内层形状涨，到了 `cap` 就停 */
  capped: {
    params: ['a', 'b', 'cap'], note: 'min(cap, a + b·t)',
    eval: function (t, p) { return Math.min(p.cap as number, (p.a as number) + (p.b as number) * t); }
  },
  /** 台阶：到点就跳一档（精英化、解锁这类"一档一档"的东西） */
  stepped: {
    params: ['base', 'per', 'from', 'cap'], note: 'min(cap, base + max(0, t−from)·per)',
    eval: function (t, p) {
      return Math.min(p.cap as number, (p.base as number) + Math.max(0, t - (p.from as number)) * (p.per as number));
    }
  },
  /** **逐点表**：`values[t−1]` 就是第 t 间的值，中间线性插值、越界取两端。
      为什么需要它（而不是全部用公式）：这几条曲线的值会乘进**怪物生命与刷怪预算**，
      必须与改造前**逐位相同**，而"换个写法"就会换掉浮点运算顺序
      （实测第 18 间：`0.45 + 0.55·t` 得 10.35，原式 `1 + (t-1)·0.55` 得 10.350000000000001）。
      逐点表还有个好处：每个房间号的强度**摊在纸上**，调曲线时不用算。
      整数点**逐位命中原值**（p0/p1 之间插值时 k=0 或 1，只做加法不做乘除）。 */
  fromTable: {
    params: ['values'], note: '按 values 查表，中间线性插值（整数点 = 原值）',
    eval: function (t, p) {
      var v = p.values as number[];
      if (!v || !v.length) return 0;
      var x = t - 1;
      if (x <= 0) return v[0];
      if (x >= v.length - 1) return v[v.length - 1];
      var i = Math.floor(x), k = x - i;
      var p0 = v[i], p1 = v[i + 1];
      return k === 0 ? p0 : p0 + (p1 - p0) * k;
    }
  },

  /** 分段线性：在给定的点上取给定值，中间线性插值（策划最直观的一种写法） */
  piecewise: {
    params: ['at', 'values'], note: '按 `at` 的刻度取 `values`，中间线性插值',
    eval: function (t, p) {
      var at = p.at as number[], v = p.values as number[];
      if (!at || !v || at.length !== v.length || !at.length) return 0;
      if (t <= at[0]) return v[0];
      for (var i = 1; i < at.length; i++) {
        if (t <= at[i]) {
          var span = at[i] - at[i - 1];
          var k = span <= 0 ? 0 : (t - at[i - 1]) / span;
          return v[i - 1] + (v[i] - v[i - 1]) * k;
        }
      }
      return v[v.length - 1];
    }
  }
};

