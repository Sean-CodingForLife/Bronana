/** 求值：`t` 是**原始自变量**（房间号），先按 `tMin` 夹一次（夹取只有这一处） */
Curves.at = function (id, t, overrides?) {
  var c = Curves.BY_ID[id];
  if (!c) return 0;
  var p: CurveParams = c.p;
  if (overrides) {
    p = {};
    for (var k in c.p) if (Object.prototype.hasOwnProperty.call(c.p, k)) p[k] = c.p[k];
    for (var k2 in overrides) if (Object.prototype.hasOwnProperty.call(overrides, k2)) p[k2] = overrides[k2];
  }
  var shape = SHAPES[c.shape];
  if (!shape) return 0;
  var raw = Number(t);
  if (!isFinite(raw)) raw = c.tMin;
  var v = shape.eval(Math.max(c.tMin, raw), p);
  return isFinite(v) ? v : 0;
};
Curves.shapeOf = function (id) { return (Curves.BY_ID[id] || { shape: '' }).shape; };
Curves.paramsOf = function (id) { return (Curves.BY_ID[id] || { p: {} }).p; };

/**
 * 把一条曲线摊成"里程碑表"（方法论里要求的那张 `milestone table`）。
 * 为什么必须有它：曲线的**形状对不对**看公式看不出来，
 * 要看它在起点 / 早期 / 中期 / 后期 / 终点 / 越界点上的值 —— 那正是这张表。
 * @returns `{ id, shape, unit, why, rows: [{t, value, delta, ratio}] }`
 */
Curves.table = function (id, points) {
  var c = Curves.BY_ID[id];
  if (!c) return null;
  var ts = points || [1, 2, 3, 5, 8, 12, 18, 24, 30, 39, 50];
  var rows = [];
  var prev = null;
  for (var i = 0; i < ts.length; i++) {
    var v = Curves.at(id, ts[i]);
    rows.push({
      t: ts[i], value: v,
      delta: prev === null ? 0 : v - prev,
      ratio: prev === null || prev === 0 ? 0 : v / prev
    });
    prev = v;
  }
  return { id: c.id, shape: c.shape, unit: c.unit, why: c.why, params: c.p, rows: rows };
};

/**
 * **两边的对照表** —— 这一节是这个模块存在的理由。
 *
 * 玩家的曲线与怪物的曲线各自都对（都在涨），但"涨得一样快吗"没有任何一处回答。
 * 这里在给定的房间刻度上同时给出：怪有多硬（`enemy.*`）、玩家有多少级与多少张卡。
 * 于是"我在第 N 间大概是什么水平"变成一个可以讨论的数字。
 *
 * 注意它刻意**不输出"谁更强"的结论**：那需要把玩家的属性换算成 DPS/有效生命
 * （`tools/curve-audit.mjs` 用机器人实测来做那件事）。这里只把两条曲线摊平对齐 ——
 * 混淆"曲线对齐"与"数值平衡"是这类工具最常见的自欺。
 */
Curves.checkpoint = function (points) {
  var ts = points || [1, 3, 6, 10, 15, 20, 25, 30, 39];
  var rows = [];
  for (var i = 0; i < ts.length; i++) {
    var t = ts[i];
    var xp = 0;
    /* 累计经验 = 逐级求和（**离散**，与游戏里的 `xpNeeded` 同一套口径：
       这一条很重要 —— 用积分代替求和会把"升到第 N 级要多少"算错一截） */
    for (var lv = 1; lv <= t; lv++) xp += Curves.at('player.xp', lv);
    rows.push({
      room: t,
      enemyHp: Curves.at('enemy.hp', t),
      enemyDmg: Curves.at('enemy.dmg', t),
      enemySpeed: Curves.at('enemy.speed', t),
      budget: Curves.at('spawn.budget', t),
      eliteChance: Curves.at('enemy.eliteChance', t),
      xpToLevel: Curves.at('player.xp', t),
      xpCumulative: xp
    });
  }
  return rows;
};

/* =========================================================
   3. 定义期自检
   ---------------------------------------------------------
   一条抓不到错的审计等于装饰。这里查的四条，每一条都对着一个**真实的静默故障**：

     · 形状不认识 → `at()` 静默返回 0（整条曲线变成恒 0，而没有任何报错）
     · 声明了形状需要的常量却没给 → 求值出 NaN，一路传进怪物生命
     · 常量不是有限数 → 同上
     · **与改造前那条式子的逐点等价** —— 这是"表驱动"这件事本身的证明：
       `LEGACY` 里抄着重构前的那几行公式，逐个点比对。不相等就抛。
       于是"我只是把常数搬进表"从一句承诺变成一条断言；
       将来真要调曲线时，改的是表，而这里会红着提醒你"这是行为变更"。

   写 `LEGACY` 时**必须把原来的夹取一起抄下来**：第一版 `spawn.budget` 漏了
   `meter.pace` 里的 `max(1, t)`，于是 t=1 处 13 vs 22.55 —— 屏幕上看起来像
   "表算错了"，实际是**参照物写错了**。这类错必须由人读出来，所以下面每一条
   都把原式**逐字**写全。
   ========================================================= */
var LEGACY: Record<string, (t: number) => number> = {
  /* 原：`1 + (Math.max(1, t) - 1) * 0.55` —— 夹取现在只在 `at()` 里做一次，
     所以参照式写**夹取之后**的形状（这正是"两个处各夹一次"那个 bug 的教训：
     参照物必须与被测物用同一个自变量）。 */
  'meter.pace': function (t) { return 1 + (t - 1) * 0.55; },
  /* 原：`var w = equivWave(t) - 1; 1 + 0.30*w + 0.045*w*w` */
  'enemy.hp': function (t) { var w = (1 + (t - 1) * 0.55) - 1; return 1 + 0.30 * w + 0.045 * w * w; },
  /* **2026-09 行为变更**（不是重构）：`1 + 0.16 * (equivWave(t) - 1)` → 系数 0.16 改成 0.37。
     为什么改：实测 生命:伤害 = `26.9 : 4.34` = **6.2 : 1**，而七款同类游戏的区间是
     0.3:1 ~ 1.5:1（Brotato 1:1 · RoR2 1.5:1 · 杀戮尖塔 1:1.8 · Hades 1:3.3）。
     6.2:1 是"只涨血、伤害基本平"的形状 —— 而那一类（以撒 / 地牢 / VS）的**生命**
     涨幅只有 2~3×，本作却用了 Brotato 的量级（×27）。借了别人的形状、用了第三家的量级。
     改完：r39 伤害 ×8.73（原 ×4.34），比值 **26.9 : 8.73 = 3.08 : 1**。
     实测依据（24 局机器人）：改动前"中间 16–30 波整整 15 个波次只有 1 局死亡"，
     把伤害抬起来之后死亡铺满整条曲线（见 docs/scaling-benchmarks.md 与 tools/curve-audit.mjs）。 */
  'enemy.dmg': function (t) { return 1 + 0.37 * ((1 + (t - 1) * 0.55) - 1); },
  /* 原：`Math.min(1.35, 1 + 0.012 * (equivWave(t) - 1))` */
  'enemy.speed': function (t) { return Math.min(1.35, 1 + 0.012 * ((1 + (t - 1) * 0.55) - 1)); },
  /* 原：`Math.min(0.24, Math.max(0, (t - 4) * 0.028))` */
  'enemy.eliteChance': function (t) { return Math.min(0.24, Math.max(0, (t - 4) * 0.028)); },
  /* 原：`Math.round((13 + ew*9 + ew*ew*0.55) * mods)`，`ew = equivWave(t) ≥ 1`。
     所以 t=1 处的预算是 **22.55**（13+9+0.55），不是 13 —— 第一版就是在这里抄错的。 */
  'spawn.budget': function (t) {
    /* 与 `fromTable` 同一条路：先把房间号换算成旧波次、**取整**、再算预算。
       为什么取整也照抄：表是逐点的，查 t 会落到 floor(t) 那一项上，
       不取整的话 t=1.55 处两边会差一个插值量（实测 25.70 vs 28.27）。 */
    var ew = 1 + (Math.floor(t) - 1) * 0.55;
    return 13 + ew * 9 + ew * ew * 0.55;
  },
  /* 原：`6 + Math.pow(level, 1.34) * 2.6`（`Stats.xpNeeded` 外面还有一层 Math.round） */
  'player.xp': function (t) { return 6 + Math.pow(Math.max(0, t), 1.34) * 2.6; }
};
/* 参考式**只在这一处**。为什么把它暴露出去：`test/curves.mjs` 的"逐点等价"那一条
   以前**自己抄了一份**（注释写着"逐字抄自改造前的源码"），于是同一句话在仓库里有两份 ——
   改曲线要同时改 `LEGACY` 和测试里的 `REF`，漏一处就"红在一处、绿在另一处"。
   实测踩到过：R37 那轮把 `enemy.dmg` 的系数从 0.16 抬到 0.37，`LEGACY` 改了、`REF` 忘了。
   现在测试直接读它，只负责验"表 == LEGACY"。 */
Curves.LEGACY = LEGACY;

/* 容差白名单：**默认 0（逐位相同）**。
   唯一的例外是 `spawn.gapTighten`（分段线性在 22.5 处的插值会有 1e-16 的舍入），
   而它只出现在**出怪间隔**里 —— 那是一个连续量、且下游紧接着就是 `rnd()`，
   差 1e-16 不会让任何一帧的判定翻面。`enemy.*` 与 `player.*` 一律零容差：
   它们乘在生命、伤害与经验上，差一点就是"这一刀少 1 点"。
   两档分开写，是为了不给自己留"反正差得不多"的余地。 */
var TOL: Record<string, number> = {
  'spawn.gapTighten': 1e-9
};

/** 逐点表能覆盖到第几间（表格形状才有；其余返回 0） */
function tableLen(c: CurveDef): number {
  var v = c.p.values as number[] | undefined;
  return (c.shape === 'fromTable' && v && v.length) ? v.length : 0;
}

Curves.audit = function () {
  var problems: string[] = [];
  var seen: Record<string, boolean> = Object.create(null);
  for (var i = 0; i < Curves.LIST.length; i++) {
    var c = Curves.LIST[i];
    if (!c.id) problems.push('第 ' + i + ' 条曲线没有 id');
    if (seen[c.id]) problems.push('曲线 id 重复：' + c.id);
    seen[c.id] = true;
    if (!c.unit) problems.push(c.id + ' 没有单位（"×3.2"与"3.2 秒"是两回事）');
    if (!c.why) problems.push(c.id + ' 没有 why —— 说不出它在回答哪个设计问题的曲线不该存在');
    var shape = SHAPES[c.shape];
    if (!shape) { problems.push(c.id + ' 的形状没登记：' + c.shape); continue; }
    for (var pi = 0; pi < shape.params.length; pi++) {
      var key = shape.params[pi];
      if (!(key in c.p)) problems.push(c.id + ' 缺形状要求的常量 ' + key + '（求值会出 NaN）');
      else if (typeof c.p[key] === 'number' && !isFinite(c.p[key] as number)) {
        problems.push(c.id + ' 的常量 ' + key + ' 不是有限数：' + c.p[key]);
      }
    }
    for (var k in c.p) {
      if (!Object.prototype.hasOwnProperty.call(c.p, k)) continue;
      if (shape.params.indexOf(k) < 0) problems.push(c.id + ' 多了一个形状不认识的常量 ' + k + '（写错了名字？）');
    }
    /* 逐点等价：抽样覆盖早期 / 中期 / 后期 / 越界。
       **从 t=1 起**：第 0 间不是真实输入（房间号从 1 起），
       而曲线在 t<1 处靠形状里的夹取兜底 —— 拿一个不存在的输入去要求等价没有意义。
       容差分两档，因为**不是所有曲线都该逐位相同**（见下面 TOL 的注释）。 */
    var legacy = LEGACY[c.id];
    if (!legacy) continue;
    var tol = TOL[c.id] === undefined ? 0 : TOL[c.id];
    var pts = [1, 2, 3, 5, 8, 12, 18, 22, 23, 24, 30, 39, 50, 80, 120, 144, 1e6];
    var tlen = tableLen(c);
    for (var p2 = 0; p2 < pts.length; p2++) {
      var t = pts[p2];
      var got = Curves.at(c.id, t);
      /* 表外**只查封顶**：逐点表在 `t > tlen` 处"取最后一个值"，
         那是一条款**有意**的封顶（"第 145 间之后不再长"）—— 它与原式不同是设计，
         不是漂移。所以这一档必须单独判，而不是把容差放大（放大等于不查）。 */
      if (tlen && t > tlen) {
        var cap = Curves.at(c.id, tlen);
        if (got !== cap) {
          problems.push(c.id + ' 在第 ' + t + ' 间越出表格（' + tlen + ' 项）后没有停在封顶值：' + got + ' vs ' + cap);
        }
        continue;
      }
      var want = legacy(t);
      if (!(Math.abs(got - want) <= tol)) {
        problems.push(c.id + ' 在 t=' + t + ' 处与改造前的式子不等：' + got + ' vs ' + want +
          '（表驱动的**前提**是值逐位相同；要改曲线就同时改 LEGACY 并说明这是行为变更）');
        break;
      }
    }
  }
  if (Curves.LIST.length < 8) problems.push('曲线表太小（' + Curves.LIST.length + ' 条）：一边的成长拼不全');
  var domains: Record<string, number> = Object.create(null);
  for (var d = 0; d < Curves.LIST.length; d++) domains[Curves.LIST[d].domain] = (domains[Curves.LIST[d].domain] || 0) + 1;
  if (!domains.enemy) problems.push('没有一条怪物侧的曲线');
  if (!domains.player) problems.push('没有一条玩家侧的曲线');
  if (!domains.spawn) problems.push('没有一条刷怪节奏的曲线');
  return {
    ok: problems.length === 0, problems: problems,
    counts: { curves: Curves.LIST.length, shapes: Object.keys(SHAPES).length, domains: Object.keys(domains).length, legacy: Object.keys(LEGACY).length }
  };
};

var verdict = Curves.audit();
if (!verdict.ok) throw new Error('curves.ts 曲线表自检失败：\n' + verdict.problems.join('\n'));
SelfCheck.register('Curves', Curves.audit);

